SELECT
    COUNT(*) AS countries_without_rivers
FROM countries c
LEFT JOIN countries_rivers cr
    ON c.country_code = cr.country_code
WHERE cr.river_id IS NULL;

/* * **INNER JOIN** – връща само редовете, които имат съвпадение и в двете таблици.

* **LEFT JOIN** – връща всички редове от лявата таблица и съвпадащите от дясната; ако няма съвпадение, стойностите отдясно са `NULL`.

* **RIGHT JOIN** – връща всички редове от дясната таблица и съвпадащите от лявата; ако няма съвпадение, стойностите отляво са `NULL`.

* **FULL JOIN** (FULL OUTER JOIN) – връща всички редове от двете таблици; несъвпадащите части се попълват с `NULL`.

* **CROSS JOIN** – връща всички възможни комбинации между редовете на двете таблици (картезианско произведение).

* **SELF JOIN** – таблица се свързва сама със себе си чрез alias, за да се сравняват или свързват нейни редове.
 */